package espanol.cp02conceptosdeorientacionaobjetos.ejercicios.desarrollo.ejerciciotres.utilidades;

public class AyudaMatematica {

    public static int cuadrado(int numero) {
        return numero * numero;
    }

    public static boolean esPar(int numero) {
        if (numero % 2 == 0) {
            return true;
        } else
            return false;
    }

    
}
