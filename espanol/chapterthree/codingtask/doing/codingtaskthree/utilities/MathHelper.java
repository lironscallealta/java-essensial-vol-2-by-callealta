package espanol.chapterthree.codingtask.doing.codingtaskthree.utilities;

public class MathHelper {

    public static int square(int number) {
        return number * number;
    }

    public static boolean isEvent(int number) {
        if (number % 2 == 0) {
            return true;
        } else
            return false;
    }

    
}
